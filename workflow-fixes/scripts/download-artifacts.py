#!/usr/bin/env python3
"""
download-artifacts.py - Downloads and unpacks GitHub Actions build artifacts
for inspection and local audit verification.
"""

import argparse
import io
import os
import subprocess
import sys
import zipfile

try:
    import requests
except ImportError:
    print("Error: 'requests' module is required. Install via: pip install requests")
    sys.exit(1)

# Ensure stdout supports UTF-8 on Windows
if sys.platform.startswith("win"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass


def get_auth_token():
    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if not token:
        try:
            res = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True, check=False)
            if res.returncode == 0 and res.stdout.strip():
                token = res.stdout.strip()
        except Exception:
            pass
    if not token:
        try:
            if sys.platform.startswith("win"):
                import winreg
                key = winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Environment")
                token, _ = winreg.QueryValueEx(key, "GH_TOKEN")
        except Exception:
            pass
    return token


def main():
    parser = argparse.ArgumentParser(description="Download artifacts generated by a GitHub Actions run.")
    parser.add_argument("run_id", help="GitHub Actions Run ID to fetch artifacts for")
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "sajuptpm/node1"),
                        help="GitHub repository in 'owner/repo' format (default: sajuptpm/node1)")
    parser.add_argument("--output-dir", default="workflow-fixes/downloaded-artifacts",
                        help="Destination directory to save extracted artifacts")

    args = parser.parse_args()
    token = get_auth_token()
    if not token:
        print("ERROR: GitHub authentication token not found. Set GH_TOKEN or login with 'gh auth login'.")
        sys.exit(1)

    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }

    url = f"https://api.github.com/repos/{args.repo}/actions/runs/{args.run_id}/artifacts"
    resp = requests.get(url, headers=headers)
    if resp.status_code != 200:
        print(f"Failed to fetch artifacts for run {args.run_id}: HTTP {resp.status_code} ({resp.text})")
        sys.exit(1)

    artifacts = resp.json().get("artifacts", [])
    if not artifacts:
        print(f"No artifacts found for run {args.run_id}.")
        return

    dest_dir = os.path.join(args.output_dir, str(args.run_id))
    os.makedirs(dest_dir, exist_ok=True)

    print(f"\nFound {len(artifacts)} artifact(s) for Run {args.run_id}:")
    for art in artifacts:
        name = art["name"]
        size_bytes = art["size_in_bytes"]
        art_id = art["id"]
        download_url = art["archive_download_url"]

        print(f"Downloading artifact '{name}' (ID: {art_id}, Size: {size_bytes} bytes)...")
        down_resp = requests.get(download_url, headers=headers, stream=True)
        if down_resp.status_code == 200:
            target_subfolder = os.path.join(dest_dir, name)
            os.makedirs(target_subfolder, exist_ok=True)
            with zipfile.ZipFile(io.BytesIO(down_resp.content)) as z:
                z.extractall(target_subfolder)
                print(f"✓ Extracted {len(z.namelist())} file(s) into: {target_subfolder}")
        else:
            print(f"Failed to download artifact '{name}': HTTP {down_resp.status_code}")

    print(f"\nAll artifacts downloaded to: {dest_dir}\n")


if __name__ == "__main__":
    main()
